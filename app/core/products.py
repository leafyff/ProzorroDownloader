"""Родовий тип товару з опису позиції.

Ту саму річ замовники називають десятком способів: «Миші», «Мишка», «Миша»,
«Миша безпровідна», «Комп'ютерне обладнання (миша дротова)». Через це таблиця
товарів розсипалася на сотні рядків по одній позиції, і побачити ринок у ній
було неможливо.

Причин розбіжностей три, і кожна лікується окремо:

1. **Текст.** Апостроф буває чотирьох накреслень (``'``, ``’``, ``ʼ``, ``` ` ```),
   регістр довільний, у описі трапляються латинські літери замість кирилиці
   («Haкопичувач» з латинською H). Це знімає :func:`normalize`.
2. **Морфологія.** «Монітор» і «Монітори» — те саме слово. Шаблони довідника
   тому записані основами («клавіатур»), а для незнайомих слів працює
   :func:`head_noun` — перший іменник фрази з відрізаним закінченням.
3. **Синоніми й скорочення.** «БФП» = «Багатофункціональний пристрій»,
   «мишка» = «миша». Тут допомагає лише довідник ``data/product_types.json``.

**Чому зіставляємо весь опис, а не його початок.** Кожна п'ята позиція
починається з коду ДК021 — «30230000-0 Комп'ютерне обладнання (монітор)», —
і справжня назва товару стоїть у дужках наприкінці. Правило «перші слова
кирилицею» давало на таких описах сміття («Комп'ютерне обладнання», «Код за
дк», «Дк»).

**Чому вирішує позиція, а не порядок у довіднику.** Опис часто називає кілька
речей, і українською першою стоїть головна, а далі йде уточнення: «кабель для
монітора» — це кабель, «кулер для процесора» — кулер, «килимок для мишки» —
килимок, «клавіатура для ноутбука» — клавіатура. Тому з усіх знайдених типів
перемагає той, чий шаблон стоїть у описі найраніше. Перевірено на живих даних:
правило «перший тип за порядком у довіднику» відносило кабелі до моніторів, а
кулери до процесорів.

Виняток описується явно — полем ``beats``: «Накопичувач SSD USB Type-C 2TB»
починається зі слова «накопичувач», але це SSD, тож тип ``Накопичувач SSD``
перебиває загальний ``Накопичувач`` незалежно від позиції. Таких пар одиниці, і
вони записані в довіднику, а не в коді.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache

from ..paths import BUNDLED_DATA

#: Усі накреслення апострофа, які трапляються в описах.
APOSTROPHES = "’ʼ‘`´'"

#: Латинські літери, якими в описах трапляються кириличні (та сама форма).
#: «Haкопичувач», «Koмплект» — наслідок копіювання з чужих таблиць.
LOOKALIKE = str.maketrans({
    "a": "а", "c": "с", "e": "е", "i": "і", "o": "о", "p": "р", "x": "х", "y": "у",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "I": "І", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
})

#: Код ДК021 будь-де в описі — разом із «ДК 021:2015» перед ним. Замовники
#: вставляють його і на початку, і в дужках посеред тексту.
_CPV_ANY = re.compile(r"(?:код\s+за\s+)?(?:дк\s*021[:\s]*\d{0,4}[:\s]*)?\b\d{8}\s*[-–]?\s*\d?\b")

#: Загальні назви класів ДК021: це заголовок, а не товар. Опис
#: «30230000-0 Комп'ютерне обладнання (монітор)» — це монітор.
CLASS_NAMES = (
    "комп'ютерне обладнання", "комп'ютерного обладнання", "комп'ютерна техніка",
    "комп'ютерної техніки", "обчислювальна техніка", "машини для обробки даних",
    "апаратна частина", "апаратної частини", "офісна та комп'ютерна техніка",
    "екрани комп'ютерних моніторів та консолі", "екрани комп'ютерних моніторів",
)
_SPLIT = re.compile(r"[^\w'\-]+")
_CYR_WORD = re.compile(r"^[А-Яа-яЇїІіЄєҐґ'’\-]+$")

#: Слова, які не називають товару: службові, загальні та назви класів ДК021.
STOP_WORDS = {
    "для", "в", "у", "з", "із", "та", "і", "й", "на", "до", "від", "по", "при", "або",
    "код", "коди", "дк", "лот", "шт", "згідно", "тип", "типу", "комплекті", "складі",
    "комплектації", "придбання", "закупівля", "постачання", "обладнання", "техніка",
    "товар", "товари", "машини", "апаратна", "частина", "різне", "інше",
}

#: Закінчення іменників — знімаємо, щоб «монітори» і «монітор» стали одним.
#: Довші йдуть першими: інакше «ами» ніколи не спрацює через «и».
_ENDINGS = ("ами", "ями", "ові", "еві", "ах", "ях", "ів", "їв", "ом", "ем", "ою", "ею",
            "и", "і", "ї", "а", "я", "у", "ю", "е", "о")

#: Закінчення прикметників: в українській вони стоять перед іменником, тож
#: «системний блок» — це «блок», а не «системний».
_ADJECTIVE = ("ий", "ій", "ова", "ове", "ові", "ний", "на", "не", "ні", "льна", "льний",
              "чний", "чна", "ська", "ський", "их", "ими", "ого", "ому", "ої")


@lru_cache(maxsize=1)
def catalog() -> list[tuple[str, tuple[str, ...], tuple[str, ...]]]:
    """Довідник типів: ``[(назва, (шаблони…), (кого перебиває…))…]``."""
    try:
        with open(BUNDLED_DATA / "product_types.json", "r", encoding="utf-8") as fh:
            book = json.load(fh)
    except (OSError, ValueError):
        return []
    out: list[tuple[str, tuple[str, ...], tuple[str, ...]]] = []
    for entry in book.get("types") or []:
        name = str(entry.get("name") or "").strip()
        patterns = tuple(str(p).lower() for p in (entry.get("patterns") or []) if p)
        beats = tuple(str(b) for b in (entry.get("beats") or []) if b)
        if name and patterns:
            out.append((name, patterns, beats))
    return out


def normalize(text: str) -> str:
    """Опис у вигляді, придатному для зіставлення: нижній регістр, один апостроф.

    Прибирає також код ДК021 і загальну назву класу («комп'ютерне обладнання»,
    «машини для обробки даних»). Без цього кожна п'ята позиція «класифікується»
    саме ними: опис «30230000-0 Комп'ютерне обладнання (монітор)» — це монітор,
    і назва класу тут лише службовий заголовок.
    """
    low = str(text or "").translate(LOOKALIKE).lower()
    for ch in APOSTROPHES:
        low = low.replace(ch, "'")
    low = low.replace("«", " ").replace("»", " ").replace('"', " ")
    low = re.sub(r"\s+", " ", low).strip()
    low = _CPV_ANY.sub(" ", low)
    for phrase in CLASS_NAMES:
        low = low.replace(phrase, " ")
    return re.sub(r"\s+", " ", low).strip(" :—–-()")


def by_catalog(text: str) -> str:
    """Тип із довідника або порожній рядок.

    Перемагає найраніший збіг у описі; за однакової позиції — вищий у
    довіднику. Типи, які інший знайдений тип перебиває полем ``beats``,
    з розгляду вибувають.
    """
    low = normalize(text)
    if not low:
        return ""
    found = []
    for order, (name, patterns, beats) in enumerate(catalog()):
        hits = [(at, -len(p)) for p in patterns for at in (_at(low, p),) if at >= 0]
        if hits:
            at, size = min(hits)
            found.append((at, size, order, name, beats))
    if not found:
        return ""
    beaten = {name for *_head, beats in found for name in beats}
    alive = [f for f in found if f[3] not in beaten] or found
    # Найраніший збіг; за однакової позиції — довший шаблон, бо він точніший
    # («комп'ютерна миша» проти «комп'ютер»), і аж потім порядок у довіднику.
    alive.sort(key=lambda f: f[:3])
    return alive[0][3]


def _at(low: str, pattern: str) -> int:
    """Позиція шаблону в описі або ``-1``.

    Короткі шаблони («пк», «дбж», «ssd») шукаються лише як окремі слова:
    підрядком вони знаходилися б усередині інших і давали хибні типи.
    """
    if len(pattern) > 3:
        return low.find(pattern)
    match = re.search(r"(?<![\w'])" + re.escape(pattern) + r"(?![\w'])", low)
    return match.start() if match else -1


def head_noun(text: str) -> str:
    """Перший іменник фрази з відрізаним закінченням.

    Запасний варіант для того, чого немає в довіднику. Прикметники в
    українській стоять перед іменником, тож «твердотільний накопичувач» — це
    «накопичувач»; беремо перше слово, яке не схоже на прикметник.
    """
    words = [w for w in _SPLIT.split(normalize(text))
             if w and w not in STOP_WORDS and _CYR_WORD.match(w)]
    if not words:
        return ""
    noun = next((w for w in words if not _is_adjective(w)), words[0])
    return _stem(noun)


def _is_adjective(word: str) -> bool:
    return len(word) > 5 and word.endswith(_ADJECTIVE)


def _stem(word: str) -> str:
    for end in _ENDINGS:
        if len(word) - len(end) >= 4 and word.endswith(end):
            return word[:-len(end)]
    return word


def product_group(text: str) -> str:
    """Родовий тип товару: довідник, а якщо він мовчить — перший іменник.

    Порожній рядок означає, що з опису не видно нічого, крім службових слів.
    """
    name = by_catalog(text)
    if name:
        return name
    noun = head_noun(text)
    return noun[:1].upper() + noun[1:] if noun else ""
